'use strict';
const assert = require('node:assert/strict');
const path = require('node:path');
const { pathToFileURL } = require('node:url');

module.exports = async function verifyRegistration({ browser, address }) {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' });
  await context.route('https://**/*', route => route.abort());
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', issue => errors.push(issue.message));
  const fill = async (email = 'new.learner@example.com') => {
    await page.locator('#full-name').fill('New Learner');
    await page.locator('#email').fill(email);
    await page.locator('#password').fill('practice-only-42');
    await page.locator('#confirm-password').fill('practice-only-42');
  };
  await page.goto(`${address}/course-details.html?id=html`);
  await page.locator('[data-auth-link]').click();
  await page.waitForSelector('#signup-form');
  assert.match(page.url(), /sign-up.html\?next=course-details/);
  await page.locator('#signup-submit').click();
  assert.equal(await page.locator('#full-name').getAttribute('aria-invalid'), 'true');
  await fill();
  await page.locator('#password').fill('short');
  await page.locator('#signup-submit').click();
  assert.match(await page.locator('#password-error').textContent(), /at least 8/);
  await page.locator('#password').fill('practice-only-42');
  await page.locator('#confirm-password').fill('not-the-same');
  await page.locator('#signup-submit').click();
  assert.match(await page.locator('#confirm-password-error').textContent(), /don’t match/);
  await page.locator('#confirm-password').fill('practice-only-42');
  await page.locator('#signup-submit').click();
  await page.waitForSelector('.details-lessons');
  assert.match(page.url(), /course-details.html\?id=html$/);
  assert.equal(await page.locator('#learning-count').textContent(), '0');
  assert.equal(await page.locator('.profile-name').textContent(), 'New Learner');
  const account = await page.evaluate(() => window.STUDIO_AUTH.account);
  const records = await page.evaluate(() => localStorage.getItem('mycourses.local-accounts.v1'));
  assert.ok(!records.includes('practice-only-42'));
  assert.equal(JSON.parse(records)[0].hash.length, 64);
  await page.locator('.details-start').click();
  await page.locator('[data-action="complete"]').click();
  await page.keyboard.press('Escape');
  await page.locator('.main-nav [data-route="profile"]').click();
  assert.equal(await page.locator('#profile-form [name="email"]').inputValue(), 'new.learner@example.com');
  assert.equal(await page.locator('#profile-form [name="email"]').getAttribute('readonly'), '');
  await page.locator('.session-panel a').click();
  await page.waitForSelector('#signout-success:not([hidden])');
  await page.locator('#signout-success a').click();
  await page.locator('#email').fill('NEW.LEARNER@example.com');
  await page.locator('#password').fill('wrong-password');
  await page.locator('#signin-submit').click();
  await page.waitForSelector('#auth-error:not([hidden])');
  await page.locator('#password').fill('practice-only-42');
  await page.locator('#signin-submit').click();
  await page.waitForSelector('.continue-card');
  assert.equal(await page.locator('#learning-count').textContent(), '1');
  assert.equal(await page.evaluate(() => window.STUDIO_AUTH.account.id), account.id);
  assert.equal(await page.evaluate(() => JSON.parse(localStorage.getItem(window.STUDIO_AUTH.storageKey('mycourses.learning-studio.v1'))).enrollments.html.completed.length), 1);
  const firstKey = await page.evaluate(() => window.STUDIO_AUTH.storageKey('mycourses.workspace.v1'));
  await page.evaluate(key => localStorage.setItem(key, JSON.stringify({ notes: [], sessions: [], joinedPaths: ['frontend'] })), firstKey);
  const other = await context.newPage();
  await other.goto(`${address}/index.html#profile`);
  await other.waitForSelector('#profile-form');
  await page.goto(`${address}/sign-up.html`);
  await fill('NEW.LEARNER@example.com');
  await page.locator('#signup-submit').click();
  await page.waitForSelector('#auth-error:not([hidden])');
  assert.match(await page.locator('#auth-error').textContent(), /already exists/);
  await fill('second.learner@example.com');
  await page.locator('#full-name').fill('Second Learner');
  await page.locator('#signup-submit').click();
  await page.waitForSelector('.course-card');
  await other.waitForFunction(() => document.querySelector('.profile-name')?.textContent === 'Second Learner');
  assert.equal(await page.locator('#learning-count').textContent(), '0');
  assert.notEqual(await page.evaluate(() => window.STUDIO_AUTH.storageKey('mycourses.workspace.v1')), firstKey);
  assert.equal(await page.evaluate(() => localStorage.getItem(window.STUDIO_AUTH.storageKey('mycourses.workspace.v1'))), null);
  await page.goto(`${address}/sign-in.html`);
  await page.locator('#demo-signin').click();
  await page.waitForSelector('.continue-card');
  assert.equal(await page.locator('#learning-count').textContent(), '2');
  assert.equal(await page.evaluate(() => window.STUDIO_AUTH.storageKey('mycourses.learning-studio.v1')), 'mycourses.learning-studio.v1');
  for (const theme of ['light', 'dark']) {
    await page.goto(`${address}/register.html`);
    await page.waitForSelector('#signup-form');
    await page.evaluate(theme => window.STUDIO_APPEARANCE.set(theme), theme);
    for (const width of [1440, 1024, 768, 390, 320]) {
      await page.setViewportSize({ width, height: 1000 });
      assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), `Registration ${theme} overflows at ${width}`);
      if (process.env.STUDIO_SCREENSHOT_DIR && [1440, 390].includes(width)) await page.screenshot({ path: path.join(process.env.STUDIO_SCREENSHOT_DIR, `sign-up-${theme}-${width}.png`), fullPage: true });
    }
  }
  await page.goto(pathToFileURL(path.join(__dirname, '../register.html')).href);
  await page.waitForSelector('#signup-form');
  await fill('file.learner@example.com');
  await page.locator('#signup-submit').click();
  await page.waitForSelector('.course-card');
  assert.equal(await page.locator('.profile-name').textContent(), 'New Learner');
  assert.deepEqual(errors, []);
  await context.close();
  console.log('PASS: registration validation, confirmation, duplicate emails, password hashing, return links, local sign-in, account/profile integration, independent progress and notebooks, account switching, file entry, and responsive themes.');
};
